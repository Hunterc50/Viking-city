"""Writes every asset in assets.py to meshes/<Slot>.glb.
Usage: python3 tools/meshgen/build.py [--obj] [Slot ...]   (no slots = all)
--obj also writes meshes/obj/<Slot>.obj/.mtl/.png for other 3D tools."""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from assets import ASSETS, SLOTS  # noqa: E402
from people import SETTLERS, settler  # noqa: E402
from mesh import write_glb, write_obj  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "meshes")


def main(args):
    obj = "--obj" in args
    names = [a for a in args if a != "--obj"]
    os.makedirs(OUT, exist_ok=True)
    if obj:
        os.makedirs(os.path.join(OUT, "obj"), exist_ok=True)
    built = []
    for name in names or ASSETS:
        mesh = ASSETS[name]()
        n = write_glb(os.path.join(OUT, name + ".glb"), [(name, mesh)])
        if obj:
            write_obj(os.path.join(OUT, "obj", name), [(name, mesh)], name + ".png")
        built.append((name, mesh))
        print(f"{name:20s} {n:6d} triangles")
    if not names:
        # settlers: four pieces each that ride on the villager rig
        people = [(slot, settler(g, k)) for slot, (g, k) in SETTLERS.items()]
        os.makedirs(os.path.join(OUT, "settlers"), exist_ok=True)
        for slot, pieces in people:
            write_glb(os.path.join(OUT, "settlers", slot + ".glb"), [(slot, pieces)])
        write_rig(people)
        # everything in one file: import once, every slot comes along
        n = write_glb(os.path.join(OUT, "VikingAssets.glb"), [(name, mesh) for name, mesh in built if name in SLOTS] + people)
        print(f"{'VikingAssets':20s} {n:6d} triangles (all slots and settlers)")


def write_rig(people):
    """src/shared/SettlerRig.luau: each settler piece's size and centre in its
    rig part's space, so the game can place an imported piece exactly."""
    import numpy as np

    lines = [
        "-- Generated by tools/meshgen/build.py. Do not edit by hand.",
        "-- For each settler mesh piece: its size and its centre, in the space of",
        "-- the villager rig part it rides on (studs, full adult size).",
        "return {",
    ]
    for slot, pieces in people:
        lines.append(f"\t{slot} = {{")
        for piece, mesh in pieces:
            pts = np.array([p for t in mesh.tris for p in t[:3]])
            lo, hi = pts.min(0), pts.max(0)
            c, sz = (lo + hi) / 2, hi - lo
            lines.append(f"\t\t{piece} = {{ size = Vector3.new({sz[0]:.3f}, {sz[1]:.3f}, {sz[2]:.3f}), centre = Vector3.new({c[0]:.3f}, {c[1]:.3f}, {c[2]:.3f}) }},")
        lines.append("\t},")
    lines.append("}")
    with open(os.path.join(ROOT, "src", "shared", "SettlerRig.luau"), "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1:])
